'''
Reinclude metal-only co-binder systems into v2_plinder_5A_v2split/{split}/ by
moving them back from v2_plinder_5A_v2split_rejected/{split}/.

Reads the survivor lists generated by `list_metal_only_cobinders.py`:
    v2_plinder_5A_v2split/logs/metal_only_cobinder_{train,val,test}.txt

Then featurizes only the newly-added dirs (skip_existing handles the rest).
'''
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, '/home/mhjang/workspace/flex')

from equiflex.dataprep.featurize_data import main as featurize_main

ROOT = Path('/home/mhjang/workspace/flex/v2_plinder_5A_v2split')
REJ  = Path('/home/mhjang/workspace/flex/v2_plinder_5A_v2split_rejected')
LOGS = ROOT / 'logs'
SPLITS = ['train', 'val', 'test']


def move_back():
    summary = {}
    for split in SPLITS:
        ids_fp = LOGS / f'metal_only_cobinder_{split}.txt'
        if not ids_fp.exists():
            print(f'[{split}] survivor file missing'); continue
        ids = [l.strip() for l in ids_fp.read_text().splitlines() if l.strip()]
        moved = already = no_src = 0
        for sid in ids:
            dst = ROOT / split / sid
            if dst.exists():
                already += 1; continue
            src = REJ / split / sid
            if not src.exists():
                no_src += 1; continue
            shutil.move(str(src), str(dst))
            moved += 1
        summary[split] = {'requested': len(ids), 'moved': moved,
                           'already_present': already, 'no_source': no_src}
        print(f'[{split}] moved={moved}  already={already}  no_source={no_src}')
    (LOGS / 'metal_reinclude_summary.json').write_text(json.dumps(summary, indent=2))
    return summary


def featurize():
    for split in SPLITS:
        data_dir = ROOT / split
        if not data_dir.exists(): continue
        print(f'\n=== featurize:{split} on {data_dir} ===')
        featurize_main(
            data_dir=str(data_dir),
            n_jobs=-1,
            skip_existing=True,
            cleanup_invalid=True,
            run_esm3=True,
            run_unimol=True,
            unimol_size='1.1B',
            device='cuda',
            strict=True,
        )


def main():
    move_back()
    featurize()


if __name__ == '__main__':
    main()
